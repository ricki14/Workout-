-- LEVEL v51 — setup una tantum per lo Studio PT
-- Compatibile con le tabelle esistenti: profiles, trainer_links, workout_records.
-- Non cancella né modifica i codici già assegnati.

create extension if not exists pgcrypto;

-- Un codice personale per ogni profilo. I codici esistenti vengono mantenuti.
alter table public.profiles
  add column if not exists client_code text;

create unique index if not exists profiles_client_code_unique
  on public.profiles (client_code)
  where client_code is not null;

-- Le schede assegnate vengono salvate separatamente dai record di allenamento.
create table if not exists public.trainer_plans (
  trainer_id uuid not null references public.profiles(id) on delete cascade,
  client_id uuid primary key references public.profiles(id) on delete cascade,
  plan jsonb not null,
  updated_at timestamptz not null default now()
);

create unique index if not exists trainer_links_pair_unique on public.trainer_links (trainer_id, client_id);

alter table public.trainer_plans enable row level security;
revoke all on public.trainer_plans from anon, authenticated;


-- Archivio permanente delle versioni precedenti delle schede assegnate dal PT.
create table if not exists public.trainer_plan_history (
  id bigint generated by default as identity primary key,
  trainer_id uuid not null references public.profiles(id) on delete cascade,
  client_id uuid not null references public.profiles(id) on delete cascade,
  plan jsonb not null,
  archived_at timestamptz not null default now()
);
create index if not exists trainer_plan_history_pair_date_idx
  on public.trainer_plan_history (trainer_id, client_id, archived_at desc);
alter table public.trainer_plan_history enable row level security;
revoke all on public.trainer_plan_history from anon, authenticated;

create or replace function public.trainer_get_client_plan_history(p_athlete_id uuid)
returns table(id bigint, plan jsonb, archived_at timestamptz)
language plpgsql security definer set search_path = public, auth
as $$
begin
  if not exists (select 1 from public.trainer_links where trainer_id=auth.uid() and client_id=p_athlete_id) then
    raise exception 'Atleta non collegato a questo studio';
  end if;
  return query select h.id, h.plan, h.archived_at
    from public.trainer_plan_history h
    where h.trainer_id=auth.uid() and h.client_id=p_athlete_id
    order by h.archived_at desc;
end;
$$;

-- Sincronizza automaticamente ogni nuova registrazione con profiles.
create or replace function public.level_sync_profile()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_role text;
  v_code text;
begin
  v_role := case
    when lower(coalesce(new.raw_user_meta_data->>'account_type','')) in ('pt','trainer')
      then 'trainer'
    else 'client'
  end;

  select p.client_code into v_code
  from public.profiles p where p.id = new.id;

  if v_code is null or btrim(v_code) = '' then
    v_code := upper(substr(encode(gen_random_bytes(8), 'hex'), 1, 8));
  end if;

  insert into public.profiles as p (id, email, role, client_code)
  values (new.id, new.email, v_role, v_code)
  on conflict (id) do update
    set email = excluded.email,
        role = case
          when lower(coalesce(new.raw_user_meta_data->>'account_type','')) in ('pt','trainer') then 'trainer'
          when lower(coalesce(new.raw_user_meta_data->>'account_type','')) in ('atleta','athlete','client') then 'client'
          else p.role
        end,
        client_code = coalesce(nullif(p.client_code,''), excluded.client_code);

  return new;
end;
$$;

drop trigger if exists level_sync_profile_trigger on auth.users;
create trigger level_sync_profile_trigger
after insert or update of email, raw_user_meta_data on auth.users
for each row execute function public.level_sync_profile();

-- Allinea i profili già esistenti ai metadati Auth e assegna un codice solo se manca.
insert into public.profiles as p (id, email, role, client_code)
select
  u.id,
  u.email,
  case
    when lower(coalesce(u.raw_user_meta_data->>'account_type','')) in ('pt','trainer') then 'trainer'
    else 'client'
  end,
  upper(substr(encode(gen_random_bytes(8), 'hex'), 1, 8))
from auth.users u
on conflict (id) do update
set email = excluded.email,
    role = case
      when excluded.role = 'trainer' then 'trainer'
      else p.role
    end,
    client_code = coalesce(nullif(p.client_code,''), excluded.client_code);

-- Codice studio del PT: riusa profiles.client_code esistente.
create or replace function public.trainer_get_my_code()
returns text
language plpgsql
security definer
set search_path = public, auth
as $$
declare v_code text;
begin
  if auth.uid() is null then raise exception 'Accesso richiesto'; end if;

  update public.profiles
  set role = 'trainer',
      client_code = coalesce(nullif(client_code,''), upper(substr(encode(gen_random_bytes(8),'hex'),1,8)))
  where id = auth.uid()
    and role = 'trainer'
  returning client_code into v_code;

  if v_code is null then
    select client_code into v_code from public.profiles
    where id = auth.uid() and role = 'trainer';
  end if;

  if v_code is null then raise exception 'Il profilo non è configurato come PT'; end if;
  return v_code;
end;
$$;

-- Elenco degli atleti collegati e relativa scheda.
create or replace function public.trainer_dashboard_clients()
returns table (
  id uuid,
  full_name text,
  email text,
  plan jsonb,
  session_count bigint
)
language sql
security definer
set search_path = public, auth
as $$
  select p.id,
         coalesce(u.raw_user_meta_data->>'full_name', split_part(coalesce(p.email,u.email,''),'@',1), 'Atleta') as full_name,
         coalesce(p.email,u.email,'') as email,
         tp.plan,
         (select count(*) from public.workout_records wr where wr.user_id=p.id) as session_count
  from public.trainer_links tl
  join public.profiles p on p.id=tl.client_id
  left join auth.users u on u.id=p.id
  left join public.trainer_plans tp on tp.client_id=p.id and tp.trainer_id=tl.trainer_id
  where tl.trainer_id=auth.uid()
  order by p.created_at desc;
$$;

-- Collega un atleta al PT che possiede il codice.
create or replace function public.athlete_link_to_trainer(p_code text)
returns boolean
language plpgsql
security definer
set search_path = public, auth
as $$
declare v_trainer uuid;
begin
  if auth.uid() is null then raise exception 'Accesso richiesto'; end if;
  if exists (select 1 from public.profiles where id=auth.uid() and role='trainer') then
    raise exception 'Un account PT non può collegarsi come atleta';
  end if;

  select id into v_trainer
  from public.profiles
  where role='trainer' and upper(client_code)=upper(btrim(p_code))
  limit 1;

  if v_trainer is null then raise exception 'Codice PT non valido'; end if;
  if v_trainer=auth.uid() then raise exception 'Non puoi collegarti al tuo stesso account'; end if;

  insert into public.trainer_links (trainer_id, client_id)
  values (v_trainer, auth.uid())
  on conflict do nothing;

  return true;
end;
$$;

-- Restituisce { "plan": ... } come si aspetta il frontend.
create or replace function public.athlete_get_assigned_plan()
returns jsonb
language sql
security definer
set search_path = public, auth
as $$
  select jsonb_build_object('plan', tp.plan)
  from public.trainer_links tl
  join public.trainer_plans tp on tp.trainer_id=tl.trainer_id and tp.client_id=tl.client_id
  where tl.client_id=auth.uid()
  order by tp.updated_at desc
  limit 1;
$$;

create or replace function public.trainer_get_client_records(p_athlete_id uuid)
returns setof public.workout_records
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if not exists (
    select 1 from public.trainer_links
    where trainer_id=auth.uid() and client_id=p_athlete_id
  ) then raise exception 'Atleta non collegato a questo studio'; end if;

  return query
  select wr.* from public.workout_records wr
  where wr.user_id=p_athlete_id
  order by wr.date desc, wr.created_at desc;
end;
$$;

create or replace function public.trainer_save_client_plan(p_athlete_id uuid, p_plan jsonb)
returns boolean
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if not exists (
    select 1 from public.trainer_links
    where trainer_id=auth.uid() and client_id=p_athlete_id
  ) then raise exception 'Atleta non collegato a questo studio'; end if;

  -- Archivia la versione corrente prima di sostituirla; non archivia se è identica.
  insert into public.trainer_plan_history (trainer_id, client_id, plan, archived_at)
  select tp.trainer_id, tp.client_id, tp.plan, now()
  from public.trainer_plans tp
  where tp.client_id=p_athlete_id
    and tp.trainer_id=auth.uid()
    and tp.plan is distinct from p_plan;

  insert into public.trainer_plans (trainer_id, client_id, plan, updated_at)
  values (auth.uid(), p_athlete_id, p_plan, now())
  on conflict (client_id) do update
    set trainer_id=excluded.trainer_id,
        plan=excluded.plan,
        updated_at=now();

  return true;
end;
$$;

